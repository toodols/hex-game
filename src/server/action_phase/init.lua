local ReplicatedStorage = game:GetService "ReplicatedStorage"
local ServerScriptService = game:GetService "ServerScriptService"

local types = require(ReplicatedStorage.Shared.types)
local util = require(ReplicatedStorage.Shared.util)
local hex_grid_mod = require(ReplicatedStorage.Shared.hex_grid)
local items_mod = require(ReplicatedStorage.Shared.items)

local server_types = require(ServerScriptService.Server.types)
local server_entity_mod = require(ServerScriptService.Server.entity)
local server_util = require(ServerScriptService.Server.util)
local updates_mod = require(ServerScriptService.Server.updates)
local computed_mod = require(ServerScriptService.Server.computed)

local handle_exchange_actions = require(script.exchange_actions).handle_exchange_actions
local handle_ability_actions = require(script.ability_actions).handle_ability_actions
local handle_try_promote_actions = require(script.try_promote_actions).handle_try_promote_actions
local handle_advance_research_actions = require(script.advance_research_actions).handle_advance_research_actions

type HexGrid = types.HexGrid
type EntityId = types.EntityId
type ActionState = server_types.ActionState
type EntityAction = server_types.EntityAction
type TeamId = types.TeamId
type System = server_types.System

function run_action_phase(grid: HexGrid)
	local t0 = tick()
	local action_state = {
		queue = {},
		dirty_entities = {},
		dead_entities = {},
		decayable_entities = {},
	} :: ActionState

	computed_mod.compute_influences(grid)

	for _, entity in grid.entities do
		if entity.status ~= "blueprint" and entity.owner ~= grid.neutral_team and entity.decayable then
			action_state.decayable_entities[entity.id] = true
		end

		for _, decision in entity.queued_decisions do
			table.insert(action_state.queue, decision)
			server_util.mark_dirty_for_everyone(action_state, entity.id)
		end
		entity.queued_decisions = {}
		local server_behavior = server_entity_mod.registry[entity.type]
		server_behavior.tick(entity, grid, action_state)

		-- queue all scaffolds for advancement
		if entity.status == "scaffold" then
			table.insert(action_state.queue, {
				type = "try_promote_scaffold",
				entity_id = entity.id,
			})
		end
	end

	for _, action in
		util.table_extract(action_state.queue, function(a: EntityAction)
			return a.type == "deconstruct"
		end)
	do
		local entity = grid.entities[action.entity_id]
		if entity.is_decaying then
			table.insert(action_state.queue, action)
		else
			updates_mod.push_buffer(grid)
			server_entity_mod.remove_entity(grid, entity, action_state)
			updates_mod.pop_buffer(grid)
		end
	end

	for _, cell in grid.cells do
		if cell.type == "portal" then
			local max_steps = cell.portal.open_time + cell.portal.close_time
			cell.portal.steps = (cell.portal.steps + 1) % max_steps
			if cell.portal.steps < cell.portal.open_time then
				cell.portal.open = true
			else
				cell.portal.open = false
			end
		end
	end

	-- if scaffold is queued for decon, try_promote_scaffold gets added to the action queue, but the entity is removed afterwards, not good

	computed_mod.compute_systems(grid)
	computed_mod.compute_influences(grid)
	for _, entities in grid.systems do
		local system = {
			entities = entities,
			overflow_items = {},
			power = 0,
			team = grid.entities[next(entities) :: any].owner,
		} :: System

		-- mark blueprints neighboring the system for promotion
		for neighbor in
			server_util.get_neighbors_set(
				grid,
				util.table_flat(util.table_map(util.table_keys(system.entities), function(id)
					return grid.entities[id].coordinates
				end))
			)
		do
			if grid.cells[neighbor] then
				for entity_id in grid.cells[neighbor].entities do
					local entity = grid.entities[entity_id]
					if entity.owner == system.team and entity.status == "blueprint" and not entity.autogenerated then
						table.insert(action_state.queue, {
							type = "try_promote_blueprint",
							entity_id = entity_id,
						})
					end
				end
			end
		end

		-- promote blueprints on portals
		for _, entity_id in util.table_keys(system.entities) do
			local entity = grid.entities[entity_id]
			local cell = grid:get_cell(entity.primary_coordinate)
			if cell.type == "portal" and cell.portal.open then
				for _, coord in cell.portal.group do
					if hex_grid_mod.coords_eq(coord, entity.primary_coordinate) then
						continue
					end
					local connected_cell = grid:get_cell(coord)
					for _, connected_entity_id in connected_cell.entities do
						local connected_entity = grid.entities[connected_entity_id]
						if
							connected_entity.owner == system.team
							and connected_entity.status == "blueprint"
							and not connected_entity.autogenerated
						then
							table.insert(action_state.queue, {
								type = "try_promote_blueprint",
								entity_id = connected_entity_id,
							})
						end
					end
				end
			end
		end

		local old_queue
		local iterations = 0
		local MAX_ALLOWED_ITERATIONS = 100
		local function should_terminate(): boolean
			if iterations > MAX_ALLOWED_ITERATIONS then
				warn "MAX_ALLOWED_ITERATIONS reached"
				return true
			end
			iterations += 1
			if #old_queue ~= #action_state.queue then
				return false
			end
			for i, action in old_queue do
				if action ~= action_state.queue[i] then
					return false
				end
			end
			return true
		end

		-- essentially, attempt to fulfill as many actions as possible in a certain order
		-- only stopping once none can be fulfilled anymore

		-- This might enter an infinite loop if in 2n iteration it moves action A to the end, then in iteration 2n+1 it moves action B to the end

		repeat
			old_queue = {}
			for _, action in action_state.queue do
				table.insert(old_queue, action)
			end

			handle_exchange_actions(grid, action_state, system)
			handle_ability_actions(grid, action_state, system)
			handle_try_promote_actions(grid, action_state, system)
			handle_advance_research_actions(grid, action_state, system)

			-- add overflow items to inventory
			for _, open_inventory_entity in
				util.table_filter_map(util.table_keys(system.entities), function(entity_id)
					local inventory = grid.entities[entity_id].inventory
					if inventory and inventory.capacity > #inventory.items then
						return grid.entities[entity_id]
					end
					return nil
				end)
			do
				if #system.overflow_items == 0 then
					break
				end
				items_mod.inventory_deposit(open_inventory_entity.inventory, system.overflow_items)
			end
		until should_terminate()

		-- then discard all the actions that shouldn't carry over
		local _discarded = util.table_extract(action_state.queue, function(action)
			return table.find({
				"try_promote_blueprint",
				"try_promote_scaffold",
			}, action.type) ~= nil
		end)
	end

	updates_mod.push_buffer(grid)
	for entity_id in action_state.dead_entities do
		server_entity_mod.remove_entity(grid, grid.entities[entity_id], action_state)
	end

	computed_mod.compute_systems(grid)

	-- entity decaying
	for _, entities in grid.systems do
		local has_heart = false
		for entity_id in entities do
			local entity = grid.entities[entity_id]
			if entity.type == "heart" or entity.type == "infinite_source" then
				has_heart = true
			end
		end

		for neighbor in
			server_util.get_neighbors_set(
				grid,
				util.table_flat(util.table_map(util.table_keys(entities), function(id)
					return grid.entities[id].coordinates
				end))
			)
		do
			if grid.cells[neighbor] then
				for entity_id in grid.cells[neighbor].entities do
					local entity = grid.entities[entity_id]
					if entity.status == "scaffold" then
						action_state.decayable_entities[entity_id] = false
					end
				end
			end
		end

		for entity_id in entities do
			if has_heart then
				action_state.decayable_entities[entity_id] = false
			end
		end
	end

	-- status effect decay
	for entity_id, entity in grid.entities do
		if next(entity.effects) == nil then
			continue
		end
		for effect_type, effect in entity.effects do
			if effect_type == "shield" then
				effect.duration -= 1
				if effect.duration <= 0 then
					entity.effects[effect_type] = nil
				end
			end
		end
		server_util.mark_dirty_for_everyone(action_state, entity_id)
	end

	updates_mod.push_buffer(grid)
	for entity_id, should_decay in action_state.decayable_entities do
		local entity = grid.entities[entity_id]
		if entity == nil then
			warn("entity not found", entity_id)
			continue
		end

		if should_decay then
			entity.is_decaying = true
			entity.decay += 1
			server_util.mark_dirty_for_everyone(action_state, entity_id)
			if entity.decay >= 3 then
				if entity.type == "wires" then
					server_entity_mod.remove_entity(grid, entity, action_state)
				else
					entity.owner = grid.neutral_team
					entity.decay = 0
					entity.is_decaying = false
				end
			end
		else
			if entity.is_decaying then
				entity.is_decaying = false
				entity.decay = 0
				server_util.mark_dirty_for_everyone(action_state, entity_id)
			end
		end
	end
	updates_mod.pop_buffer(grid)

	computed_mod.compute_presence(grid)
	for _, entity in grid.entities do
		if entity.status == "blueprint" then
			local cell = grid:get_cell(entity.primary_coordinate)
			if
				util.table_any(util.table_keys(cell.server_data.presence), function(team)
					if team ~= entity.owner then
						return true
					end
					return false
				end)
			then
				server_entity_mod.remove_entity(grid, entity, action_state)
			end
		end
	end
	updates_mod.pop_buffer(grid)

	computed_mod.compute_visibility(grid, action_state)

	table.insert(grid.updates_buffer[#grid.updates_buffer], {
		type = "cells",
		cells = grid.cells,
	})

	for entity_id, values in action_state.dirty_entities do
		local entity = grid.entities[entity_id]
		if entity == nil then
			-- dirty entity was probably deleted nothing to worry about
			continue
		end
		if values.everyone then
			table.insert(grid.updates_buffer[#grid.updates_buffer], {
				type = "entity_update",
				entity = entity,
			})
		else
			local targets: { TeamId } = {}
			for _, team_id in util.table_keys(values) do
				table.insert(targets, team_id)
			end
			table.insert(grid.updates_buffer[#grid.updates_buffer], {
				type = "entity_update",
				entity = entity,
				targets = targets,
			})
		end
	end

	grid.turn += 1
	table.insert(grid.updates_buffer[#grid.updates_buffer], {
		type = "turn",
		turn = grid.turn,
		highest_turn = grid.highest_turn,
	})
	local updates_copy = table.clone(grid.updates_buffer[#grid.updates_buffer])

	updates_mod.flush_updates(grid)
	grid:purge_dead_entities()

	return {
		elapsed = tick() - t0,
		updates = updates_copy,
	}
end

return {
	run_action_phase = run_action_phase,
}
