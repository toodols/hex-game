export type Entity = {
	active: boolean?,

	type: string,
	coordinates: { CubicCoordinate },
	primary_coordinate: CubicCoordinate,
	id: string,
	-- 0 - 5
	rotation: number,
	health: number,
	max_health: number,
	inventory: Inventory?,

	effects: { Effect },

	-- factory only
	current_recipe: string?,

	-- proxy only
	disguise: EntityId?,

	-- Whether this building's primary abilities are enabled
	enabled: boolean?,

	-- for heart and extractor
	should_output: number?,
	--- extractor only
	deposit: CellType?,

	-- entities enter decay when there is no longer a heart
	decay: number?,
	is_decaying: boolean?,
	decayable: boolean?,

	-- laboratory only
	researches: Researches?,

	-- Witness only
	charges: number?,

	-- An entity in blueprint phase
	cost: { [Item]: number },
	cost_fulfilled: { [Item]: number },

	-- for vertex so that vertex generated by a building cannot get abused for free vertex
	autogenerated: boolean?,

	status: "blueprint" | "scaffold" | "complete",
	is_destroyed: boolean?,
	build_time: number,

	owner: TeamId,
	queued_decisions: { Decision },

	-- for clients: .always_visible or .always_visible_for[team_id]
	always_visible: boolean?,
	server_data: {
		is_disguise_of: EntityId?,
		-- whether this entity is always visible regardless of whether the cell it is on is visible
		always_visible: boolean?,
		-- whether this entity is always visible for a specific team
		always_visible_for: { [TeamId]: boolean? },
		-- timestamp of when it was first requested to be constructed
		requested_at: number,

		will_die: { death_type: string },
	},
}

