export type CellType = "basic" | "bar_deposit" | "tar_deposit" | "vit_deposit" | "rad_deposit" | "portal"

type Portal = {
	group: { CubicCoordinate },
	open: boolean,
	steps: number,
	open_time: number,
	close_time: number,
}

export type CellTeamVisibility = {
	-- visible by virtue of having an entity right next to this cell
	contact: boolean?,
	-- visible by virtue of this team having fog disabled
	fogless: boolean?,
	-- visible by virtue of this cell being a portal and a connected portal being occupied by the team
	portal: boolean?,
	-- illuminated by scout, or (later on) torch
	illumination: boolean?,

	-- set by compute_visibility so action_phase can generate a minimal list of entity updates
	changed_to_true: boolean?,
}

export type HexCell = {
	type: CellType,
	entities: { [EntityId]: boolean },
	coordinate: CubicCoordinate,

	owner: TeamId?,

	-- client only property created in server.serialize.serialize_cell_for_team
	visible_for_team: boolean?,
	buildable_for_team: boolean?,

	portal: Portal?,

	influences: {
		[EntityId]: boolean,
	},
	server_data: {
		-- a presence is imposed by an enemy team, and prevents a player from building on that cell
		presence: {
			[TeamId]: boolean,
		},
		visibility: {
			[TeamId]: CellTeamVisibility,
		},
	},
}

