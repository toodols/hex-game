export type Damage = {
	from: EntityId?,
	damage_type: ("physical" | "healing")?,
	amount: number,
	-- Whether this damage ignores shields
	-- Note piercing still respects layered entities (building above vertex)
	piercing: boolean?,
	-- Whether this damage can kill the entity
	nonlethal: boolean?,
	-- Whether this damage can affect friendly entities
	friendly_fire: boolean?,
}

