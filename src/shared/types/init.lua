	type: "shield",
	health: number,
	duration: number,
}

export type AnimationState = {
	type: "idle",
	step: number,
}

export type Entity = {
	type: string,
	coordinates: { CubicCoordinate },
	primary_coordinate: CubicCoordinate,
	id: string,
	-- 0 - 5
	rotation: number,
	health: number,
	max_health: number,
	inventory: Inventory?,

	effects: { [EffectType]: Effect },

	animation_state: AnimationState?,

	-- factory only
	current_recipe: string?,

	enabled: boolean?,

	-- for heart and maybe extractor
	should_output: number?,

	-- entities enter decay when there is no longer a heart
	decay: number?,
	is_decaying: boolean?,
	decayable: boolean?,

	-- laboratory only
	researches: Researches?,

	-- Witness only
	charges: number?,

	-- An entity in blueprint phase
	cost: { [Item]: number },
	cost_fulfilled: { [Item]: number },

	-- for wires so that wires generated by a building cannot get abused for free wires
	autogenerated: boolean?,

	status: "blueprint" | "scaffold" | "complete",
	is_destroyed: boolean?,
	build_time: number,

	owner: TeamId,
	queued_decisions: { Decision },

	server_data: {
		-- whether this entity is always visible regardless of whether the cell it is on is visible
		always_visible: boolean?,
		-- timestamp of when it was first requested to be constructed
		requested_at: number,
	},
}

