export type CellType = "basic" | "bar_deposit" | "tar_deposit" | "vit_deposit" | "rad_deposit" | "portal"

type Portal = {
	group: { CubicCoordinate },
	open: boolean,
	steps: number,
	open_time: number,
	close_time: number,
}

export type HexCell = {
	type: CellType,
	entities: { [EntityId]: boolean },
	coordinate: CubicCoordinate,

	owner: TeamId?,

	-- client only property created in server.serialize.serialize_cell_for_team
	visible_for_team: boolean?,
	buildable_for_team: boolean?,

	portal: Portal?,

	influences: {
		[EntityId]: boolean,
	}?,
	server_data: {
		-- a presence is imposed by an enemy team, and prevents a player from building on that cell
		presence: {
			[TeamId]: boolean,
		},

		-- an influence are created by support buildings, and provide boosts to nearby entities
		influences: {
			[EntityId]: boolean,
		},

		visibility: {
			[TeamId]: {
				-- visible by virtue of contact (r=2)
				contact: boolean?,

				-- visible by virtue of having full visibility on the map (all cells)
				full: boolean?,

				-- visible by virtue of occupying a portal
				portal: boolean?,
			},
		},
	},
}

